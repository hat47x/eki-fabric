// Package evidence は、製品価値を示す指標（ADR-0008）を追記型の観測記録から導出する。
//
// 指標を「何台のワーカーがつながったか」や「総FLOPS」で測ると、資源を利用者へ返すこと（reclaim）が
// 性能低下として扱われ、分散しないという判定も「使われなかった」として数えられてしまう。
// そこでADR-0008は、次の五つを主指標とする。
//
//   - 利用者が端末へ戻ってから計算資源が縮小されるまでの時間（reclaim latency）
//   - 受理された結果のうち、検証されたものの割合（verified share）
//   - Suitabilityゲートが各判定を返した件数。「分散しない」という判定も正常な成果として数える
//   - reclaimやワーカー離脱の後のリトライで、権限主体（Authority）が増えた回数。製品不変条件により0でなければならない
//   - 検証済みの資源提供実績（Contribution Record）の件数
//
// 入力は、追記だけされる観測の列（[]Observation）である。このパッケージは観測を書き換えず、
// 観測の時刻もすべて呼び出し側から受け取る。時計は読まない。
//
// 各指標は、導出に使った観測のIDを必ず持つ。利用者は、どの記録からその数字が出たかをたどれる。
// 指標は成功の証明そのものではなく、記録された事実の集計である。
//
// 次の扱いは、どちらとも取れる場合に保守的な側へ倒している。
//
//   - 未検証の申告（Claim）は、検証済みの指標に数えない。受理された結果が検証されていなければ、
//     検証の割合の分母には入るが分子には入らない。
//   - 受理されなかった結果は、検証されていても検証の割合に含めない。
//   - 同じ観測IDが二度現れた場合は、導出全体を拒否する。同じ結果IDに判定が二度記録された場合も同様である。
//     後の記録が前の記録を黙って上書きしたように見せないためである。
//   - 完了していないreclaimは、所要時間から除外せず「未完了」として一覧に残す。
//     捨ててしまうと、利用者が戻った後にまだ実行が残っている状態が見えなくなる。
//   - 分母が0の割合は、0パーセントとも100パーセントとも表さず、「割合がない」として返す。
//   - 観測がないリトライは、権限の増加が起きなかったことの証拠にはしない。
//
// 補助指標（ワーカー数など）は、主指標とは別の型Secondaryで返す。
// 補助指標だけで成功を主張しないよう、型の段階で分けてある。
//
// このパッケージは、I/Oを行わず、環境変数を読まず、時計を読まず、goroutineを起動しない。
// 標準ライブラリ以外に依存せず、statestore、control、adaptersの各パッケージからは何も読み込まない。
// 記録が正しいこと（結果が実際に受理されたこと、検証が実際に行われたこと）は、呼び出し側の検証層が保証する。
// このパッケージはその判定を信頼して集計するだけである。
//
// 配線（#57の縦断スライスへの接続）は、#57が存在するまで行わない。
//
// 正本: plan/adr/0008-product-value-evidence-metrics.md

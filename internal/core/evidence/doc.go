// Package evidence は、製品価値を示す指標（ADR-0008）のうち、追記型の観測記録から導出できる部分を計算する。
//
// 指標を「何台のワーカーがつながったか」や「総FLOPS」で測ると、資源を利用者へ返すこと（reclaim）が
// 性能低下として扱われ、分散しないという判定も「使われなかった」として数えられてしまう。
// そこでADR-0008は、次の五つを主指標とする。
//
//   - 利用者が端末へ戻ってから計算資源が縮小されるまでの時間（reclaim latency）
//   - 受理された結果のうち、検証されたものの割合（verified share）
//   - Suitabilityゲートが各判定を返した件数。「分散しない」という判定も正常な成果として数える
//   - reclaimやワーカー離脱の後のリトライで、権限主体（Authority）が増えた回数や、同じ作業が二度実行された回数。製品不変条件により0でなければならない
//   - 検証済みの資源提供実績（Contribution Record）の件数
//
// このパッケージは五つの指標すべてを完全には導出しない。次の四つは未実装か部分的であり、
// この範囲の数字だけを根拠に成功を主張してはならない。詳しくは「部分実装の範囲」を参照する。
//
// 入力は、追記だけされる観測の列（[]Observation）である。このパッケージは観測を書き換えず、
// 観測の時刻もすべて呼び出し側から受け取る。時計は読まない。
//
// 各指標は、導出に使った観測のIDを必ず持つ。利用者は、どの記録からその数字が出たかをたどれる。
// 検証済みと宣言された結果は検証記録のID（VerificationRecordID）を、検証済みと宣言された資源提供実績は
// 根拠となる事実のID（SupportingFactIDs）を必ず持つ。これらのIDも、導出に使われた根拠として
// 各指標のSourceIDsに現れる。指標は成功の証明そのものではなく、記録された事実の集計である。
//
// 次の扱いは、どちらとも取れる場合に保守的な側へ倒している。
//
//   - 未検証の申告（Claim）は、検証済みの指標に数えない。受理された結果が検証されていなければ、
//     検証の割合の分母には入るが分子には入らない。
//   - 受理されなかった結果は、検証されていても検証の割合に含めない。
//   - 同じ観測IDが二度現れた場合は、導出全体を拒否する。同じ結果IDに判定が二度記録された場合も同様である。
//     後の記録が前の記録を黙って上書きしたように見せないためである。
//   - 検証済みと宣言された結果に検証記録のIDがない場合、また検証済みの資源提供実績に根拠の事実がない場合は、導出全体を拒否する。
//     根拠をたどれない数字を出さないためである。
//   - 検証記録のIDや根拠の事実のIDが、観測のIDと同じ値である場合は、導出全体を拒否する。
//     どちらもSourceIDsに現れるため、同じ値では根拠の指す先が決まらないからである。
//   - リトライの原因は、reclaim、ワーカー離脱、その他の三つに限る。原因のないリトライは「その他」に
//     黙って数えず、導出全体を拒否する。
//   - 完了していないreclaimは、所要時間から除外せず「未完了」として一覧に残す。
//     捨ててしまうと、利用者が戻った後にまだ実行が残っている状態が見えなくなる。
//   - 分母が0の割合は、0パーセントとも100パーセントとも表さず、「割合がない」として返す。
//   - 観測がないリトライは、権限の増加が起きなかったことの証拠にはしない。
//
// 部分実装の範囲
//
// 次の四つは、ADR-0008の指標定義のうち、このパッケージがまだ満たしていない部分である。
//
//   - reclaimの突き合わせ（reclaim cross-check）: ADR-0008は、端末側ガバナの記録と、ワーカー上で実際に
//     観測した結果を突き合わせるよう定め、中央の記録だけでは判定しないとする。このパッケージは
//     ガバナの記録（GovernorReclaim）だけを読み、ワーカー上の観測との突き合わせは行わない。
//   - 保証水準（Assurance Level）: ADR-0008は、検証された割合に保証水準と検証方式を付けるよう定める。
//     このパッケージの検証済みの判定は真偽値だけであり、保証水準と検証方式は導出しない。
//   - Audit の根拠種別: ADR-0008は、根拠として Audit 記録、ガバナログ、Verification 記録を挙げる。
//     このパッケージは Audit 記録を観測の種別として持たないため、その種別の根拠は指標に現れない。
//   - FLOPSと資源利用率: ADR-0008は補助指標として報告するよう定める。このパッケージは導出しない。
//     ADR-0008は指標の名前と、根拠として挙げる記録の種類を定めるが、観測の種別は定めていない。
//     観測の種別（GovernorReclaim、ResultDecision、SuitabilityDecision、RetryEvent、ContributionRecord）は
//     このパッケージが定めるものであり、そのどれも、FLOPSや利用率の値を持たないため、この記録からは計算できない。
//     導出には資源使用量を記録する観測の種別が要り、その設計は未決である。この基準は未決のまま残し、
//     黙って欠けているのではないことを明示する。
//
// Audit の根拠種別と FLOPS・利用率は、この範囲では実装せず、未決（open）のまま残す。
// 指標の定義は ADR-0008 のままであり、このパッケージでは変えていない。
//
// 補助指標（ワーカー数など）は、主指標とは別の型Secondaryで返す。補助指標だけで成功を主張しないよう、
// 型の段階で分けてある。
//
// このパッケージは、I/Oを行わず、環境変数を読まず、時計を読まず、goroutineを起動しない。
// 標準ライブラリ以外に依存せず、statestore、control、adaptersの各パッケージからは何も読み込まない。
// これらの制約は、guard_test.go がgo/astで包括的に検査する。
// 記録が正しいこと（結果が実際に受理されたこと、検証が実際に行われたこと）は、呼び出し側の検証層が保証する。
// このパッケージはその判定を信頼して集計するだけである。
//
// 配線（#57の縦断スライスへの接続）は、#57が存在するまで行わない。
//
// 正本: plan/adr/0008-product-value-evidence-metrics.md
